#include <iostream>

using namespace std;

// ==========================================
// EJEMPLO 1: Hola Mundo Simple
// ==========================================

int main()
{
    cout << "Hola Mundo" << endl;

    return 0;
}

// EXPLICACIÓN:
// - #include <iostream>: Incluye la librería para entrada/salida
// - using namespace std: Usa el namespace estándar
// - int main(): Función principal por donde comienza el programa
// - cout << "...": Envía texto a la pantalla
// - return 0: Indica que el programa terminó exitosamente
// - endl: Salta a una nueva línea

